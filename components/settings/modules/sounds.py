"""System sounds: on/off, volume-change click, and the sound theme — any installed theme (Ocean,
Oxygen, freedesktop…), the "Vidro" glass set (generated by vidro/sounds/make-sounds.py) or "My preset":
a theme built from the user's choices per event (files or sounds of other themes), on top of a base theme.
CLI (used by the app):  sounds.py --list | --play THEME EVENT | --play-file PATH
                        --import PATH      a theme folder/archive (.tar.gz .tar.xz .zip) or a folder/archive of loose
                                           sound files (e.g. a Windows set: "Windows Error.wav", "tada.wav"...)
                        --export THEME FILE.tar.gz      --save-preset "Name"   (my preset → a real theme)"""
import glob, json, os, re, shutil, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
from _common import flag, kread, kwrite

GROUP = 'Sounds'
DATA = os.environ.get('XDG_DATA_HOME', os.path.expanduser('~/.local/share'))
USER_SOUNDS = os.path.join(DATA, 'sounds')
GENERATOR = os.path.join(DATA, 'vidro', 'sounds', 'make-sounds.py')
CUSTOM_ID = 'vidro-custom'
EVENTS = [   # (freedesktop name, label)
    ('desktop-login', 'Entrar na sessão'), ('desktop-logout', 'Sair da sessão'),
    ('dialog-information', 'Informação'), ('dialog-question', 'Pergunta'), ('dialog-warning', 'Aviso'),
    ('dialog-error', 'Erro'), ('message-new-instant', 'Mensagem nova'), ('message-new-email', 'E-mail novo'),
    ('message-attention', 'Pedindo atenção'), ('complete', 'Concluído'), ('outcome-success', 'Sucesso'),
    ('outcome-failure', 'Falha'), ('device-added', 'Dispositivo conectado'), ('device-removed', 'Dispositivo removido'),
    ('power-plug', 'Carregador conectado'), ('power-unplug', 'Carregador removido'), ('battery-low', 'Bateria fraca'),
    ('audio-volume-change', 'Mudar o volume'), ('screen-capture', 'Captura de tela'), ('trash-empty', 'Esvaziar lixeira'),
    ('bell', 'Sino (alerta curto)'), ('alarm-clock-elapsed', 'Alarme / timer'), ('phone-incoming-call', 'Chamada'),
]
DEFAULTS = {
    'enabled': 'true',          # system sounds on/off
    'theme': 'ocean',           # installed theme id | vidro | vidro-custom (my preset)
    'volume_feedback': 'true',  # click when changing the volume
    'custom_base': 'vidro',     # my preset: theme used for the events I did not choose
}
for _e, _l in EVENTS:
    DEFAULTS[f'custom_{_e}'] = ''   # file path, or "theme:<id>" to take that event from another theme


def _dirs():
    return [USER_SOUNDS] + [os.path.join(d, 'sounds') for d in
                            (os.environ.get('XDG_DATA_DIRS') or '/usr/local/share:/usr/share').split(':')]


def _theme_dir(tid):
    for d in _dirs():
        p = os.path.join(d, tid)
        if os.path.isfile(os.path.join(p, 'index.theme')):
            return p
    return None


def _inherits(tid):
    p = _theme_dir(tid)
    if not p:
        return []
    m = re.search(r'^Inherits\s*=\s*(.*)$', open(os.path.join(p, 'index.theme'), errors='replace').read(), re.M)
    return [x.strip() for x in m.group(1).split(',') if x.strip()] if m else []


def _own(tid, event):
    p = _theme_dir(tid)
    if not p:
        return None
    for sub in ('stereo', '.', 'mono'):
        for ext in ('oga', 'ogg', 'wav', 'flac'):
            f = os.path.join(p, sub, f'{event}.{ext}')
            if os.path.exists(f):
                return os.path.realpath(f)
    return None


def resolve(tid, event, seen=None):
    """File that plays for `event` in theme `tid` (follows Inherits, then freedesktop)."""
    seen = seen or set()
    if tid in seen:
        return None
    seen.add(tid)
    f = _own(tid, event)
    if f:
        return f
    for parent in _inherits(tid) + ['freedesktop']:
        f = resolve(parent, event, seen)
        if f:
            return f
    return None


def themes():
    out, ids = [], set()
    for d in _dirs():
        for p in sorted(glob.glob(os.path.join(d, '*', 'index.theme'))):
            tid = os.path.basename(os.path.dirname(p))
            if tid in ids:
                continue
            ids.add(tid)
            m = re.search(r'^Name\s*=\s*(.*)$', open(p, errors='replace').read(), re.M)
            own = sum(1 for e, _ in EVENTS if _own(tid, e))
            out.append({'id': tid, 'name': m.group(1).strip() if m else tid, 'own': own})
    if 'vidro' not in ids:
        out.append({'id': 'vidro', 'name': 'Vidro', 'own': 0, 'pending': True})
    if CUSTOM_ID not in ids:
        out.append({'id': CUSTOM_ID, 'name': 'Meu preset', 'own': 0, 'pending': True})
    order = {'vidro': 0, CUSTOM_ID: 1}
    return sorted(out, key=lambda t: (order.get(t['id'], 2), t['name'].lower()))


def _ensure_vidro():
    dest = os.path.join(USER_SOUNDS, 'vidro')
    try:
        if open(os.path.join(dest, '.vidro-version')).read().strip() == _generator_version():
            return
    except OSError:
        pass
    if os.path.isfile(GENERATOR):
        subprocess.run(['python3', '-I', GENERATOR, dest], capture_output=True)


def _generator_version():
    try:
        m = re.search(r"^VERSION = '([^']*)'", open(GENERATOR).read(), re.M)
        return m.group(1) if m else ''
    except OSError:
        return ''


def _build_custom(cfg):
    """~/.local/share/sounds/vidro-custom: chosen files copied in, the rest inherited from the base theme."""
    dest = os.path.join(USER_SOUNDS, CUSTOM_ID)
    st = os.path.join(dest, 'stereo')
    os.makedirs(st, exist_ok=True)
    for f in glob.glob(os.path.join(st, '*')):
        os.remove(f)
    base = cfg.get('custom_base', 'vidro') or 'vidro'
    if base == 'vidro':
        _ensure_vidro()
    for e, _ in EVENTS:
        v = str(cfg.get(f'custom_{e}', '')).strip()
        src = resolve(v[6:], e) if v.startswith('theme:') else os.path.expanduser(v.replace('file://', ''))
        if src and os.path.isfile(src):
            ext = os.path.splitext(src)[1].lower() or '.oga'
            if ext not in ('.oga', '.ogg', '.wav', '.flac'):   # mp3 etc. → convert
                subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', src, '-t', '15', '-c:a', 'libvorbis', '-q:a', '5',
                                '-f', 'ogg', os.path.join(st, e + '.oga')], capture_output=True)
            else:
                shutil.copyfile(src, os.path.join(st, e + ext))
    with open(os.path.join(dest, 'index.theme'), 'w') as f:
        f.write(f'[Sound Theme]\nName=Meu preset (Vidro)\nComment=Sons escolhidos nas Configurações do Vidro\n'
                f'Inherits={base},freedesktop\nDirectories=stereo\n\n[stereo]\nOutputProfile=stereo\n')


def current():
    return {'theme': kread('kdeglobals', 'Sounds', 'Theme', 'ocean'),
            'enabled': kread('kdeglobals', 'Sounds', 'Enable', 'true'),
            'volume_feedback': kread('plasmaparc', 'General', 'AudioFeedback', 'true')}


def apply(cfg):
    theme = cfg.get('theme', 'ocean') or 'ocean'
    if theme == 'vidro':
        _ensure_vidro()
    elif theme == CUSTOM_ID:
        _build_custom(cfg)
    if kread('kdeglobals', 'Sounds', 'Theme', '') != theme:
        kwrite('kdeglobals', 'Sounds', 'Theme', theme, notify=True)
    on = 'true' if flag(cfg, 'enabled') else 'false'
    if kread('kdeglobals', 'Sounds', 'Enable', 'true') != on:
        kwrite('kdeglobals', 'Sounds', 'Enable', on, notify=True)
    fb = 'true' if flag(cfg, 'volume_feedback') else 'false'
    if kread('plasmaparc', 'General', 'AudioFeedback', 'true') != fb:
        kwrite('plasmaparc', 'General', 'AudioFeedback', fb, notify=True)


# loose files → events (Windows / macOS / generic names)
GUESS = [
    ('desktop-login', r'logon|log.?in|startup|start.?up|welcome|boot'), ('desktop-logout', r'logoff|log.?out|shut.?down|goodbye'),
    ('dialog-error', r'critical|error|stop|basso|fail'), ('dialog-warning', r'exclamation|warn|sosumi|funk'),
    ('dialog-question', r'question|asterisk'), ('dialog-information', r'^ding|information|info|ping|glass'),
    ('message-new-instant', r'notif|message|pop|tink'), ('message-new-email', r'mail'), ('complete', r'tada|complete|hero|success|done'),
    ('device-added', r'hardware.?insert|device.?(connect|add|insert)|plug.?in'), ('device-removed', r'hardware.?remove|device.?(disconnect|remov)'),
    ('trash-empty', r'recycle|trash|empty'), ('battery-low', r'battery'), ('bell', r'chord|bell|default.?beep|beep'),
    ('screen-capture', r'shutter|screenshot|capture'), ('audio-volume-change', r'volume'),
]
AUDIO = ('.oga', '.ogg', '.wav', '.flac', '.mp3', '.opus')


def _slug(name):
    import unicodedata
    n = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode()
    return re.sub(r'[^a-z0-9]+', '-', n.lower()).strip('-') or 'tema'


def _unique(sid):
    base, i = sid, 2
    while os.path.exists(os.path.join(USER_SOUNDS, sid)):
        sid = f'{base}-{i}'; i += 1
    return sid


def import_theme(path):
    """Installs a sound theme (folder/archive with index.theme) or builds one from loose sound files.
    Returns the new theme id."""
    import tarfile, tempfile, zipfile
    path = os.path.expanduser(path.replace('file://', ''))
    if os.path.isfile(path) and os.path.basename(path) == 'index.theme':
        path = os.path.dirname(path)
    tmp = None
    if os.path.isfile(path) and not path.lower().endswith(AUDIO):
        tmp = tempfile.mkdtemp(prefix='vidro-sounds-')
        if zipfile.is_zipfile(path):
            with zipfile.ZipFile(path) as z:
                for m in z.namelist():   # no absolute paths / ".." escapes
                    if not (m.startswith('/') or '..' in m.split('/')):
                        z.extract(m, tmp)
        elif tarfile.is_tarfile(path):
            with tarfile.open(path) as t:
                t.extractall(tmp, filter='data')
        else:
            raise SystemExit('formato não reconhecido')
        root = tmp
    elif os.path.isfile(path):   # a single sound file: becomes a one-sound theme
        root = tempfile.mkdtemp(prefix='vidro-sounds-'); tmp = root
        shutil.copy(path, root)
    else:
        root = path
    try:
        themes_found = [os.path.dirname(p) for p in glob.glob(os.path.join(root, '**', 'index.theme'), recursive=True)]
        os.makedirs(USER_SOUNDS, exist_ok=True)
        if themes_found:
            ids = []
            for d in themes_found:
                sid = _unique(_slug(os.path.basename(d.rstrip('/')) if d != root else os.path.basename(path).split('.')[0]))
                shutil.copytree(d, os.path.join(USER_SOUNDS, sid), symlinks=True)
                ids.append(sid)
            return ids[0]
        files = [f for f in glob.glob(os.path.join(root, '**', '*'), recursive=True) if f.lower().endswith(AUDIO)]
        if not files:
            raise SystemExit('nenhum som encontrado')
        name = re.sub(r'\.(tar\.(gz|xz|bz2|zst)|tgz|zip|txz)$', '', os.path.basename(path.rstrip('/')), flags=re.I)
        sid = _unique('importado-' + _slug(name))
        st = os.path.join(USER_SOUNDS, sid, 'stereo')
        os.makedirs(st)
        used = set()
        for event, rx in GUESS:
            for f in sorted(files):
                if f not in used and re.search(rx, os.path.splitext(os.path.basename(f))[0], re.I):
                    _copy_sound(f, os.path.join(st, event))
                    used.add(f)
                    break
        if not used:   # nothing matched: the first file becomes the information sound
            _copy_sound(sorted(files)[0], os.path.join(st, 'dialog-information'))
        with open(os.path.join(USER_SOUNDS, sid, 'index.theme'), 'w') as fh:
            fh.write(f'[Sound Theme]\nName={name}\nComment=Importado nas Configurações do Vidro\nInherits=ocean,freedesktop\n'
                     'Directories=stereo\n\n[stereo]\nOutputProfile=stereo\n')
        return sid
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)


def _copy_sound(src, dest_noext):
    ext = os.path.splitext(src)[1].lower()
    if ext in ('.oga', '.ogg', '.wav', '.flac'):
        shutil.copyfile(src, dest_noext + ('.oga' if ext == '.ogg' else ext))
    else:
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', src, '-t', '20', '-c:a', 'libvorbis', '-q:a', '5', '-f', 'ogg',
                        dest_noext + '.oga'], capture_output=True)


def export_theme(tid, dest):
    """Theme → .tar.gz with real files (links resolved; inherited events included), ready to share."""
    import tarfile, tempfile
    if not _theme_dir(tid):
        raise SystemExit(f'tema não encontrado: {tid}')
    tmp = tempfile.mkdtemp(prefix='vidro-export-')
    try:
        out = os.path.join(tmp, tid)
        os.makedirs(os.path.join(out, 'stereo'))
        for e, _ in EVENTS:
            f = resolve(tid, e)
            if f:
                shutil.copyfile(f, os.path.join(out, 'stereo', e + os.path.splitext(f)[1]))
        d = _theme_dir(tid)
        name = tid
        if d:
            m = re.search(r'^Name\s*=\s*(.*)$', open(os.path.join(d, 'index.theme'), errors='replace').read(), re.M)
            name = m.group(1).strip() if m else tid
        with open(os.path.join(out, 'index.theme'), 'w') as fh:
            fh.write(f'[Sound Theme]\nName={name}\nComment=Exportado das Configurações do Vidro\nInherits=freedesktop\n'
                     'Directories=stereo\n\n[stereo]\nOutputProfile=stereo\n')
        dest = os.path.expanduser(dest.replace('file://', ''))
        if not dest.endswith(('.tar.gz', '.tgz')):
            dest += '.tar.gz'
        with tarfile.open(dest, 'w:gz') as t:
            t.add(out, arcname=tid)
        return dest
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def save_preset(name):
    """'My preset' → a standalone theme with its own name (shows up in the list; can be exported)."""
    src = _theme_dir(CUSTOM_ID)
    if not src:
        raise SystemExit('monte o preset primeiro')
    sid = _unique(_slug(name))
    dest = os.path.join(USER_SOUNDS, sid)
    shutil.copytree(src, dest)
    p = os.path.join(dest, 'index.theme')
    t = open(p).read()
    t = re.sub(r'^Name=.*$', f'Name={name}', t, flags=re.M)
    open(p, 'w').write(t)
    return sid


def _play(path):
    if path and os.path.isfile(path):
        subprocess.Popen(['pw-play', path], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
        return True
    return False


if __name__ == '__main__':
    a = sys.argv[1:]
    if a[:1] == ['--list']:
        if not _theme_dir('vidro'):
            _ensure_vidro()
        ts = themes()
        files = {t['id']: {e: (resolve(t['id'], e) or '') for e, _ in EVENTS} for t in ts}
        print(json.dumps({'themes': ts, 'events': [{'id': e, 'label': l} for e, l in EVENTS], 'files': files}, ensure_ascii=False))
    elif a[:1] == ['--play'] and len(a) >= 3:
        if a[1] == 'vidro':
            _ensure_vidro()
        sys.exit(0 if _play(resolve(a[1], a[2])) else 1)
    elif a[:1] == ['--import'] and len(a) >= 2:
        print(import_theme(a[1]))
    elif a[:1] == ['--export'] and len(a) >= 3:
        print(export_theme(a[1], a[2]))
    elif a[:1] == ['--save-preset'] and len(a) >= 2:
        print(save_preset(a[1]))
    elif a[:1] == ['--play-file'] and len(a) >= 2:
        sys.exit(0 if _play(os.path.expanduser(a[1])) else 1)
    else:
        print(__doc__)
