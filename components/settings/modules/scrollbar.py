"""App scrollbars (Union style "vidro"). The overlay mode uses the libvidroscroll Qt plugin,
loaded by every KDE app through QT_PLUGIN_PATH (takes effect at the next login)."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from _common import CONFIG, VIDRO, flag, hex_rgba, num, write_css

GROUP = 'Scrollbar'
DEFAULTS = {
    'enabled': 'true',      # false = stock Breeze/Union scrollbar
    'mode': 'glass',        # glass | thin-neon | color
    'width': '6',           # handle thickness (px)
    'opacity': '45',        # 0-100, handle at rest
    'highlight': '80',      # 0-100, handle on hover / drag
    'roundness': '100',     # 0-100 (% of half the width)
    'track': 'false',       # show the track
    'color': '#8ab4f8',     # color for mode "color"
    'overlay': 'true',      # on top of the content, truly transparent (plugin; next login)
    'autohide': 'true',     # hide when idle (overlay only)
    'delay': '1200',        # ms idle before hiding
    'min_opacity': '0',     # % opacity when hidden
}
ENV = os.path.join(CONFIG, 'plasma-workspace', 'env', 'vidro-scrollbar.sh')
OLD_ENV = os.path.join(CONFIG, 'plasma-workspace', 'env', 'vidro-barra.sh')
PLUGIN = os.path.join(VIDRO, 'qtplugins')


def _session(enable):
    """Session script that makes KDE apps load the overlay-scrollbar plugin (next login)."""
    if os.path.exists(OLD_ENV):
        os.remove(OLD_ENV)
    if enable and os.path.isfile(os.path.join(PLUGIN, 'styles', 'libvidroscroll.so')):
        os.makedirs(os.path.dirname(ENV), exist_ok=True)
        with open(ENV, 'w') as f:
            f.write('# Vidro: overlay scrollbar (style plugin wrapping Union). Generated by vidro-config.\n'
                    f'export QT_PLUGIN_PATH="{PLUGIN}${{QT_PLUGIN_PATH:+:$QT_PLUGIN_PATH}}"\n')
    elif os.path.exists(ENV):
        os.remove(ENV)


def apply(cfg):
    _session(flag(cfg, 'enabled') and flag(cfg, 'overlay'))
    if not flag(cfg, 'enabled'):
        write_css('scrollbar', '/* off: stock scrollbar */\n')
        return
    mode = cfg.get('mode', 'glass')
    w = int(num(cfg, 'width', 2, 16, 6))
    op = num(cfg, 'opacity', 0, 100, 45) / 100
    hi = num(cfg, 'highlight', 0, 100, 80) / 100
    radius = round(w / 2 * num(cfg, 'roundness', 0, 100, 100) / 100, 1)
    pad = 3
    total = w + 2 * pad
    if mode == 'thin-neon':
        base = f'modify-color(var(--highlight-color) set-alpha {op:.3f})'
        hover = f'modify-color(var(--highlight-color) set-alpha {max(op, hi):.3f})'
        border = border_hover = 'none'
    elif mode == 'color':
        c = cfg.get('color', '#8ab4f8')
        base, hover = hex_rgba(c, op), hex_rgba(c, max(op, hi))
        border = border_hover = 'none'
    else:  # glass: frosted handle without accent color
        base = f'modify-color(var(--window-text-color) set-alpha {op * 0.55:.3f})'
        hover = f'modify-color(var(--window-text-color) set-alpha {max(op, hi) * 0.6:.3f})'
        border = f'1px solid modify-color(var(--window-text-color) set-alpha {min(1, op * 0.35):.3f})'
        border_hover = f'1px solid modify-color(var(--window-text-color) set-alpha {min(1, hi * 0.4):.3f})'
    faint = 'modify-color(var(--window-text-color) set-alpha 0.05)'
    if flag(cfg, 'overlay'):
        track = faint if flag(cfg, 'track') else 'transparent'
    else:
        track = faint if flag(cfg, 'track') else 'var(--view-background-color)'
    write_css('scrollbar', f""":root {{
    --scrollbar-size: {total}px;
    --non-interactive-scrollbar-size: {max(4, total - 4)}px;
}}
scrollbar {{
    width: {total}px;
    height: {total}px;
    padding: {pad}px;
    background-color: {track};
    &.horizontal {{ border-top: none; }}
    &.vertical {{ border-left: none; }}
    & > handle {{
        background-color: {base};
        border: {border};
        border-radius: {radius}px;
        &:hovered,
        &:pressed {{
            background-color: {hover};
            border: {border_hover};
        }}
    }}
    &.noninteractive {{
        border-left: none;
        & > handle {{ background-color: {base}; border: none; border-radius: {radius}px; }}
    }}
}}
""")
