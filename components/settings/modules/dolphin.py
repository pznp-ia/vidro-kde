"""Dolphin: no separator lines, continuous background between sidebar and files.
Only Dolphin uses it: derived Union style "vidro-dolphin" (links to the "vidro" files) + Dolphin
launchers with UNION_STYLE_NAME=vidro-dolphin. Off = Dolphin looks like the other apps."""
import glob, os, shutil, sys
sys.path.insert(0, os.path.dirname(__file__))
from _common import DATA, VIDRO, flag, hex_color, kread, kwrite, num

GROUP = 'Dolphin'
DEFAULTS = {
    'enabled': 'true',
    'separators': '0',             # 0-100: separator line visibility (0 = none)
    'unify': 'true',               # list background in the window color (Vidro scheme: affects every KDE app's lists)
    'background': 'interface',     # interface | custom — file area background
    'background_color': '#25282d', # used when background = custom
    'darken': '0',                 # 0-100: file area — 0 = same as the window, 100 = the original dark
    'spacing': '6',                # px between the panes
}
BASE = os.path.join(DATA, 'union', 'styles', 'vidro')
STYLE = os.path.join(DATA, 'union', 'styles', 'vidro-dolphin')
LAUNCHER = os.path.join(DATA, 'applications', 'org.kde.dolphin.desktop')
DBUS = os.path.join(DATA, 'dbus-1', 'services', 'org.kde.dolphin.FileManager1.service')
MARKS = ('# generated by vidro-config (module dolphin)', '# gerado por vidro-config (módulo pastas)')
SCHEME = os.path.join(DATA, 'color-schemes', 'Vidro.colors')
ORIGINAL = os.path.join(VIDRO, 'lists-original.txt')   # original list colors (to go back)
OLD_ORIGINAL = os.path.join(VIDRO, 'listas-original.txt')


def _rgb(t):
    return [int(x) for x in t.split(',')[:3]]


def _lists(darken, enable, color=None):
    """List background ([Colors:View] of the Vidro scheme): from "same as the window" (0) to the original dark (1).
    KDE only allows this in the color scheme, so it applies to the lists of every KDE app."""
    if not os.path.exists(SCHEME):
        return
    if not os.path.exists(ORIGINAL) and os.path.exists(OLD_ORIGINAL):
        os.rename(OLD_ORIGINAL, ORIGINAL)
    if not os.path.exists(ORIGINAL):
        os.makedirs(os.path.dirname(ORIGINAL), exist_ok=True)
        open(ORIGINAL, 'w').write(kread(SCHEME, 'Colors:View', 'BackgroundNormal') + '\n'
                                  + kread(SCHEME, 'Colors:View', 'BackgroundAlternate') + '\n')
    orig_normal, orig_alt = open(ORIGINAL).read().split()
    if enable:
        window = _rgb(kread(SCHEME, 'Colors:Window', 'BackgroundNormal'))
        if color:
            window = [int(color[i:i + 2], 16) for i in (1, 3, 5)]
        mix = lambda a, b: ','.join(str(round(x + (y - x) * darken)) for x, y in zip(a, b))
        normal = mix(window, _rgb(orig_normal))
        alt = mix([min(255, v + 6) for v in window], _rgb(orig_alt))
    else:
        normal, alt = orig_normal, orig_alt
    active = kread('kdeglobals', 'General', 'ColorScheme') == 'Vidro'
    for k, v in (('BackgroundNormal', normal), ('BackgroundAlternate', alt)):
        kwrite(SCHEME, 'Colors:View', k, v)
        if active:
            kwrite('kdeglobals', 'Colors:View', k, v, notify=True)


def _style(vars_css, css):
    cdir = os.path.join(STYLE, 'contents', 'css')
    shutil.rmtree(STYLE, ignore_errors=True)
    os.makedirs(cdir)
    with open(os.path.join(STYLE, 'metadata.json'), 'w') as f:
        f.write('{\n "input-type": "css",\n "input-version": 1,\n "name": "Vidro Dolphin",\n'
                ' "description": "Vidro for Dolphin: no separator lines (generated by vidro-config).",\n'
                ' "version": "1.0",\n "license": "BSD-2-Clause",\n "authors": [ "Vidro" ]\n}\n')
    base_css = os.path.join(BASE, 'contents', 'css')
    for p in glob.glob(os.path.join(base_css, '*.css')):
        if os.path.basename(p) != 'style.css':
            os.symlink(os.path.relpath(p, cdir), os.path.join(cdir, os.path.basename(p)))
    images = os.path.join(BASE, 'contents', 'images')
    if os.path.isdir(images):
        os.symlink(os.path.relpath(images, os.path.join(STYLE, 'contents')), os.path.join(STYLE, 'contents', 'images'))
    # Union resolves var() in reading order: the variables go right after defaults.css
    st = open(os.path.join(base_css, 'style.css')).read().rstrip('\n')
    st = st.replace('@import "defaults.css";', '@import "defaults.css";\n@import "dolphin-vars.css";', 1)
    with open(os.path.join(cdir, 'style.css'), 'w') as f:
        f.write(st + '\n@import "dolphin.css";\n')
    with open(os.path.join(cdir, 'dolphin-vars.css'), 'w') as f:
        f.write('/* generated by vidro-config (module dolphin) */\n' + vars_css)
    with open(os.path.join(cdir, 'dolphin.css'), 'w') as f:
        f.write('/* generated by vidro-config (module dolphin) */\n' + css)


def _launchers(enable):
    for p in (LAUNCHER, DBUS):
        if os.path.exists(p) and any(m in open(p).read() for m in MARKS):
            os.remove(p)
    if not enable:
        return
    env = 'UNION_STYLE_NAME=vidro-dolphin'
    src = '/usr/share/applications/org.kde.dolphin.desktop'
    if os.path.exists(src) and not os.path.exists(LAUNCHER):
        os.makedirs(os.path.dirname(LAUNCHER), exist_ok=True)
        s = open(src).read().replace('Exec=dolphin', f'Exec=env {env} dolphin')
        open(LAUNCHER, 'w').write(s.replace('[Desktop Entry]', '[Desktop Entry]\n' + MARKS[0], 1))
    dolphin = shutil.which('dolphin')   # no Dolphin (or a flatpak one): don't take over "open folder" of other apps
    if dolphin and not os.path.exists(DBUS):
        os.makedirs(os.path.dirname(DBUS), exist_ok=True)
        open(DBUS, 'w').write(f'{MARKS[0]}\n[D-BUS Service]\nName=org.freedesktop.FileManager1\n'
                              f'Exec=/usr/bin/env {env} {dolphin} --daemon\n')


def apply(cfg):
    if not flag(cfg, 'enabled'):
        shutil.rmtree(STYLE, ignore_errors=True)
        _launchers(False)
        _lists(1, False)
        return
    lines = num(cfg, 'separators', 0, 100, 0) / 100 * 0.18
    darken = num(cfg, 'darken', 0, 100, 0) / 100
    spacing = int(num(cfg, 'spacing', 0, 16, 6))
    border = f'modify-color(var(--window-text-color) set-alpha {lines:.3f})'
    names = ('window-border-color', 'window-inactive-border-color', 'view-border-color', 'header-border-color',
             'hairline-color', 'bar-active-border-color', 'window-active-border-color', 'header-active-border-color',
             'header-inactive-border-color')
    vars_css = ':root {\n' + ''.join(f'    --{n}: {border};\n' for n in names) + '}\n'
    css = (f'splitter {{ width: {max(1, spacing)}px; background-color: transparent; }}\n'
           'splitview handle { background-color: transparent; }\n'
           'toolbar, statusbar { border: none; border-top: none; border-bottom: none; }\n')
    color = hex_color(cfg.get('background_color'), None) if cfg.get('background') == 'custom' else None
    _lists(darken, flag(cfg, 'unify') or bool(color), color)
    # the borderless style is built on the Vidro Union style; without Union (e.g. SteamOS) only the colors apply
    if os.path.isfile(os.path.join(BASE, 'contents', 'css', 'style.css')):
        _style(vars_css, css)
        _launchers(True)
    else:
        shutil.rmtree(STYLE, ignore_errors=True)
        _launchers(False)
