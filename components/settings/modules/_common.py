"""Shared helpers for Vidro modules.

A module is a file in this folder with:
    GROUP = "Name"             group in ~/.config/vidrorc
    DEFAULTS = {key: value}    default values (strings)
    def apply(cfg): ...        cfg = dict with the group's values (defaults already merged)
    def current(): ...         optional: values read from the running system (shown in the app
                               instead of the defaults, so nothing changes until the user edits)
"""
import glob, os, re, subprocess

DATA = os.environ.get('XDG_DATA_HOME', os.path.expanduser('~/.local/share'))
CONFIG = os.environ.get('XDG_CONFIG_HOME', os.path.expanduser('~/.config'))
BIN = os.path.expanduser('~/.local/bin')
VIDRO = os.path.join(DATA, 'vidro')
CSS = os.path.join(DATA, 'union', 'styles', 'vidro', 'contents', 'css')


# ---------- values ----------
def num(cfg, key, lo, hi, default):
    """Number from cfg[key], clamped to [lo, hi]."""
    try:
        v = float(cfg.get(key, default))
    except (TypeError, ValueError):
        v = float(default)
    return max(lo, min(hi, v))


def flag(cfg, key):
    return str(cfg.get(key, 'true')).lower() in ('1', 'true', 'yes', 'on')


def hex_color(value, default):
    return value if re.fullmatch(r'#[0-9a-fA-F]{6}', value or '') else default


def hex_rgb(value, default=(138, 180, 248)):
    value = hex_color(value, '')
    return tuple(int(value[i:i + 2], 16) for i in (1, 3, 5)) if value else tuple(default)


def hex_rgba(value, alpha):
    r, g, b = hex_rgb(value)
    return f'rgba({r}, {g}, {b}, {max(0, min(1, alpha)):.3f})'


# ---------- system ----------
def run(*cmd, **kw):
    return subprocess.run(list(cmd), capture_output=True, text=True, **kw)


def kread(file, group, key, default=''):
    groups = sum((['--group', g] for g in group.split('][')), [])
    return run('kreadconfig6', '--file', file, *groups, '--key', key).stdout.strip() or default


def kwrite(file, group, key, value, notify=False):
    groups = sum((['--group', g] for g in group.split('][')), [])
    run('kwriteconfig6', *(['--notify'] if notify else []), '--file', file, *groups, '--key', key, str(value))


def kwin_reconfigure():
    run('dbus-send', '--session', '--type=method_call', '--dest=org.kde.KWin', '/KWin', 'org.kde.KWin.reconfigure')


def kwin_effect(name, enabled, reconfigure=True):
    """Enable/disable a KWin effect now and in kwinrc."""
    kwrite('kwinrc', 'Plugins', f'{name}Enabled', 'true' if enabled else 'false')
    d = ['dbus-send', '--session', '--type=method_call', '--dest=org.kde.KWin', '/Effects']
    run(*d, f'org.kde.kwin.Effects.{"loadEffect" if enabled else "unloadEffect"}', f'string:{name}')
    if enabled and reconfigure:
        run(*d, 'org.kde.kwin.Effects.reconfigureEffect', f'string:{name}')


def once(cache_name, key):
    """True if `key` differs from the last value stored under `cache_name` (and stores it).
    Used to skip slow work (theme reloads) when nothing relevant changed."""
    path = os.path.expanduser(f'~/.cache/vidro/{cache_name}')
    try:
        if open(path).read() == key:
            return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write(key)
    return True


# ---------- Union app style ("vidro") ----------
def write_css(name, text):
    """Write css/module-<name>.css in the Union style; css/vidro-modules.css imports them all
    (and is imported at the end of style.css). Running apps pick it up when reopened."""
    if not os.path.isdir(CSS):
        return False
    for old in glob.glob(os.path.join(CSS, 'modulo-*.css')) + [os.path.join(CSS, 'vidro-modulos.css')]:
        if os.path.exists(old):
            os.remove(old)   # files from the Portuguese version
    with open(os.path.join(CSS, f'module-{name}.css'), 'w') as f:
        f.write(f'/* generated by vidro-config (module {name}) - do not edit by hand */\n' + text)
    imports = ''.join(f'@import "{os.path.basename(p)}";\n' for p in sorted(glob.glob(os.path.join(CSS, 'module-*.css'))))
    with open(os.path.join(CSS, 'vidro-modules.css'), 'w') as f:
        f.write('/* generated by vidro-config */\n' + imports)
    style = os.path.join(CSS, 'style.css')
    s = open(style).read().replace('@import "vidro-modulos.css";\n', '')
    if 'vidro-modules.css' not in s:
        s = s.rstrip('\n') + '\n@import "vidro-modules.css";\n'
    open(style, 'w').write(s)
    sync_derived_styles()
    return True


def sync_derived_styles():
    """Derived styles (e.g. vidro-dolphin) link to the vidro CSS files. When a new module file
    appears and the link is missing in a derived style, Union breaks (Dolphin used to hang).
    Here every derived style gets the missing links and loses the dangling ones."""
    styles = os.path.dirname(os.path.dirname(os.path.dirname(CSS)))
    files = sorted(os.path.basename(p) for p in glob.glob(os.path.join(CSS, '*.css')) if not p.endswith('/style.css'))
    for d in glob.glob(os.path.join(styles, '*', 'contents', 'css')):
        if os.path.realpath(d) == os.path.realpath(CSS):
            continue
        if not any(os.path.islink(p) and os.path.realpath(p).startswith(os.path.realpath(CSS))
                   for p in glob.glob(os.path.join(d, '*.css'))):
            continue
        for f in files:
            target = os.path.join(d, f)
            if not os.path.lexists(target):
                os.symlink(os.path.relpath(os.path.join(CSS, f), d), target)
        for p in glob.glob(os.path.join(d, '*.css')):
            if os.path.islink(p) and not os.path.exists(p):
                os.remove(p)
        st = os.path.join(d, 'style.css')
        if os.path.isfile(st) and not os.path.islink(st):
            s = open(st).read().replace('vidro-modulos.css', 'vidro-modules.css')
            open(st, 'w').write(s)
